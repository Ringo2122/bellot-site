# сначала город (по всем пунктам: «Смолевичский р-н, г. Жодино» — Жодино), потом район; г. Минск и без области — nil
def place_of(addr, region)
  ps = PLACES[region] or return nil
  a = addr.to_s.tr('ёЁ', 'еЕ')
  p = ps.find { |_, cs, _| cs.any? { |c| a =~ /(?:(?<![А-Яа-я])[гГ]\.\s*|город\s+|\A\s*|,\s*)#{c}(?![а-я])/ } } ||
      ps.find { |_, _, st| st && a =~ /(?<![А-Яа-я])#{st}[а-я]*\s+(?:р-?н|район)/i }
  p ? p[0] : OTHER_PLACE
end

# Пункты не из TOWNS: geo.rb спрашивает область у OpenStreetMap и хранит в data/regions.json
# («Уречье|т» => «Минская область»; 0 — не нашёл или тёзки в разных областях).
PLACE_REG_FILE = File.expand_path('../data/regions.json', __dir__)
PLACE_RE = /(?:\A|[\s,.(])(гп|г\.\s?п|г|н\.\s?п|аг|д|дер|пос|п)\.?\s*([А-Я][а-я]+(?:-[А-Я]?[а-я]+)?)/

def place_reg
  $place_reg ||= (JSON.parse(File.read(PLACE_REG_FILE, encoding: 'UTF-8')) rescue {})
end

# название пункта и «т» — город или городской посёлок, «н» — деревня, агрогородок и прочие
def place_key(addr)
  m = addr.to_s.tr('ё', 'е').match(PLACE_RE) or return nil
  "#{m[2]}|#{m[1] =~ /\A(?:г|гп|г\.\s?п)\z/ ? 'т' : 'н'}"
end

