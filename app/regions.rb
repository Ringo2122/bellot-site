# Регион из адреса: 6 областей + г. Минск. Общий для build.rb, market_realty.rb, collect_all.rb.
OBLAST = { 'брест' => 'Брестская', 'витебск' => 'Витебская', 'гомел' => 'Гомельская',
           'гродн' => 'Гродненская', 'могил' => 'Могилевская', 'минск' => 'Минская' }.freeze

# Площадки пишут адрес по-разному: "Витебская обл.", "г.Витебск", "Витебский район".
def region_of(addr)
  a = addr.to_s.tr('ё', 'е')
  return 'г. Минск' if a =~ /г\.?\s*Минск(?!ая)/
  [/(\S+?)ская\s+обл/i, /(\S+?)ский\s+(?:р-?н|район)/i].each do |re|
    m = a.match(re) or next
    k = OBLAST.keys.find { |x| m[1].downcase.start_with?(x[0, 5]) }
    return OBLAST[k] + ' область' if k
  end
  k = OBLAST.keys.find { |x| a.downcase.include?(x) }
  return OBLAST[k] + ' область' if k
  # области в адресе нет («г. Речица, ул. …», «Жлобинский р-н, аг. …») — по городу или району
  t = town_region(a)
  t ? t + ' область' : a[/^[^,]+/].to_s.strip
end

# Районные центры и крупные города → область. Ищем только в названии города (после «г.», «гп», «аг.»), района
# (перед «р-н», «район») и в начале адреса — не в улицах («ул. Октябрьская» — не Октябрьский район).
TOWNS = {
  'Брестская' => %w[баранович береза березовск брест ганцевич дрогичин жабинк иванов ивацевич каменец кобрин лунинец
                    ляхович малорит пинск пружан столин белоозерск микашевич коссов давид-город],
  'Витебская' => %w[бешенкович браслав верхнедвинск глубок городок докшиц дубровен лепел лиозн миор орш полоцк новополоцк
                    постав россон сенн толочин ушач чашник шарковщин шумилин новолукомл],
  'Гомельская' => %w[брагин буда-кошелев ветк добруш ельск житкович жлобин калинкович кормян лельчиц лоев мозыр наровл
                     октябрьск петриков речиц рогачев светлогорск хойник чечерск туров василевич],
  'Гродненская' => %w[берестовиц волковыск воронов дятлов зельв ивье ивьев корелич лид мост новогруд островец ошмян свислоч
                      слоним сморгон щучин скидел березовк],
  'Минская' => %w[березин борисов вилейк вилейск воложин дзержинск клецк копыл крупк крупск логойск любан молодечн мядел
                  несвиж пуховичск марьина слуцк смолевич солигорск стародорожск старые столбц узден червен жодин фанипол заславл],
  'Могилевская' => %w[белынич бобруйск быхов глуск горецк горки дрибин кировск климович кличев костюкович краснопол кричев
                      круглян мстислав осипович славгород хотимск чаус чериков шклов]
}.freeze

def town_region(addr)
  a = addr.to_s.downcase.tr('ё', 'е')
  words = a.scan(/(?:\A|[\s,.])(?:г|гп|аг|г\.п)\.?\s*([а-я-]{3,})/).flatten +
          a.scan(/([а-я-]{4,})\s+(?:р-?н|район)/).flatten + [a[/\A\s*([а-я-]{4,})/, 1]].compact
  words.each do |w|
    TOWNS.each { |obl, stems| return obl if stems.any? { |st| w.start_with?(st) } }
  end
  nil
end
