# encoding: utf-8
#
# Площадь недвижимости из текста лота — когда у площадки нет отдельной строки «Площадь» (14.10: у 476 лотов, из них
# 339 torgi.gov.by, площадь была только в названии или описании: «общей площадью 284,6 кв.м», «Общая площадь
# (протяженность): 1389.2», «общ.пл. 274,0 кв.м.», «Торговый павильон 31 кв.м», «Площадь-99,9»).
module Area
  module_function

  NUM = '(\d{1,3}(?:[  ]\d{3})+(?:[.,]\d+)?|\d+(?:[.,]\d+)?)'
  M2 = '(?:кв\.?\s*м(?:етр[а-я]*)?\.?|м²|м2|м\.\s*кв)'
  # «общая площадь …: 1389.2», «общей площадью здания – 196,7 кв.м», «общ.пл. 2 767,2» — единица может не стоять
  TOTAL = /общ(?:[а-я]*\s+|\.\s*)(?:площад[а-я]*|пл\.)(?:\s+(?!застро|участ)[а-я]+){0,3}?(?:\s*\([^)]{0,30}\))?\s*(?:[-:–—]|составляет|равна)?\s*#{NUM}(?!\s*га\b)(?![.,]?\d)/i
  # без «общая»: «площадь 42,3 кв.м», «павильон 31 кв.м», «Площадь-99,9» (без единицы — только через знак)
  ANY = /#{NUM}\s*#{M2}|площад[а-я]*\s*[-:–—]\s*#{NUM}(?!\s*га\b)(?![.,]?\d)/i
  HA = /площад[а-я]*\s*(?:,\s*га\s*)?(?:[-:–—]\s*)?#{NUM}\s*(?:га\b)?/i
  # число относится к участку, застройке или цене «за 1 кв.м» — не площадь объекта
  NOT = /(?:участ[а-я]*|застройки|жил[а-я]*)\s*(?:[^\s.;]+\s*){0,3}\z|\bза\s*\z/i

  def num(s) s.to_s.gsub(/[  ]/, '').tr(',', '.').to_f end

  def grab(t, re)
    vals = []
    t.scan(re) do
      m = Regexp.last_match
      next if m.pre_match[-60..].to_s =~ NOT
      v = num(m.captures.compact.first)
      vals << v if v >= 1 && v < 1_000_000
    end
    vals.uniq
  end

  # land — участок: берём гектары; иначе — площадь строений (сумма по объектам лота), без площади участка
  def of(text, land: false)
    t = text.to_s.gsub(/\s+/, ' ')
    unless land
      vals = grab(t, TOTAL)
      vals = grab(t, ANY) if vals.empty?
      return vals.sum.round(1) if vals.any?
      return nil
    end
    (m = t.match(/#{HA.source}/i)) && m[0] =~ /га/ && (v = num(m[1])).positive? && v < 10_000 ? (v * 10_000).round : nil
  end
end
