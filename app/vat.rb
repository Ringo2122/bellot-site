# encoding: utf-8
#
# НДС лота — одним из пяти статусов для калькулятора (16.10). Считается при каждой сборке сайта по пометке робота
# (terms['vat'], terms['vat_add'] — со страниц площадок) и тексту лота, поэтому новые правила сразу действуют для всех лотов.
#   in   цена указана с НДС — больше ничего не доплачивается
#   add  к цене добавится НДС 20% — площадка прямо так пишет («плюс 20% НДС», «без учета НДС (НДС 20%)»)
#   may  может добавиться — «может быть увеличена на сумму НДС», «наличие НДС определяется статусом продавца», «без учета НДС»
#   no   к цене не добавляется — «не облагается», «сверху не начисляется» (beltorgi), продавец не плательщик НДС
#   nil  площадка ничего не написала
# Порядок проверки важен: у torgi.gov.by поле «с НДС», а в описании — «может быть увеличена…»: осторожный статус главнее.
module Vat
  module_function

  NO = /НДС[^.;]{0,40}?не\s*облага|не\s*облага\S*\s+НДС|НДС\s+не\s+взима|сверху\s+не\s+(?:начисля|добавля)|не\s+является\s+плательщик\S*\s+НДС|освобожд\S*\s+от\s+(?:уплаты\s+)?НДС/i
  ADD = /плюс\s*(?:\d+\s*%\s*)?НДС|\+\s*НДС|НДС\s+(?:начисляется|уплачивается|оплачивается)\s+сверх|будет\s+(?:добавлен|начислен)\S*\s+НДС|без\s+уч[её]та\s+НДС\s*\(\s*НДС\s*\d+\s*%\s*\)/i
  MAY = /увелич\S*\s+на\s+(?:сумму\s+)?(?:\d+\s*%\s*)?НДС|наличие\s+или\s+отсутствие\s+НДС|исчисляем\S*\s+сверх|без\s+(?:уч[её]та\s+)?НДС/i
  # «с НДС» в тексте лота — только рядом с ценой: «затраты оператору 787 рублей с НДС» (lotsale) — это не про цену лота;
  # между ценой и «с НДС» — до 40 знаков без точки, кроме точки в числе («143 000.00 BYN с НДС» у rtorgi)
  IN_TEXT = /(?:цен\S*|стоимост\S*|ставк\S*|указан\S*|прода[её]т\S*|реализ\S*)(?:[^.;]|\.\d){0,40}?[сc]\s+(?:уч[её]т\S*\s+)?(?:\d+\s*%\s*)?НДС|\(\s*[сc]\s+(?:уч[её]т\S*\s+)?НДС|(?:включая|в\s+том\s+числе|включа\S*)\s+НДС|НДС\s+включ[её]н/i
  IN_FIELD = /[сc]\s+(?:уч[её]т\S*\s+)?(?:\d+\s*%\s*)?НДС|включ/i   # пометка робота — уже про цену

  def kind(terms, text)
    f = terms['vat'].to_s
    d = text.to_s
    return 'no' if f =~ NO || d =~ NO
    return 'add' if f =~ ADD || d =~ ADD
    return 'may' if terms['vat_add'] || f =~ MAY || d =~ MAY
    return 'in' if f =~ IN_FIELD || d =~ IN_TEXT
    nil
  end
end
